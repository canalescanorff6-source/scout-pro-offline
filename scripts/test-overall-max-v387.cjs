'use strict';
const assert=require('node:assert/strict');
const A=require('../web/craque-accounts-v382.js'),L=require('../web/craque-account-library-v385.js');
const F=require('../web/craque-friends-v227.js'),R=require('../web/craque-card-review-v379.js');
const original=require('../web/SCOUT_V69_AUDITORIA.json').cards[0];
const card={id:'qa-max',name:'Jogador QA',position:'CA',cardId:'123456789',edition:'Edição A',maxLevel:32,pp:62};
const old=A.normalCard(card),withMax=A.normalCard({...card,maxOverall:'111'});
assert.equal(withMax.maxOverall,111,'O normalizador não pode descartar o Overall máximo informado');
assert.equal(withMax.maxOverallIdentity,A.evidenceIdentity(card));
assert(!Object.hasOwn(old,'maxOverall'),'Cadastros antigos mantêm a mesma representação');
assert.equal(A.normalCard({...card,maxOverall:''}).maxOverall,null);
for(const bad of [0,151,NaN,true,1.5])assert.throws(()=>A.normalCard({...card,maxOverall:bad}),/Overall/);
assert.equal(A.normalCard({...withMax,edition:'Edição B'}).maxOverall,null,'Outra edição não herda o máximo');
assert.equal(L.fingerprint(withMax),L.fingerprint(old),'Máximo informativo não invalida fichas de treino');
const memory=new Map(),store={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
L.saveCard(store,'primary',withMax);L.saveCard(store,'secondary',{...card,maxOverall:107});
assert.equal(A.read(store).primary.cards[0].maxOverall,111);
assert.equal(A.read(store).secondary.cards[0].maxOverall,107);
const doc=A.validate(JSON.parse(store.getItem(A.KEY)));
assert.equal(doc.primary.cards[0].maxOverall,111,'Backup/exportação conserva o valor');
L.saveCard(store,'secondary',{...A.read(store).secondary.cards[0],maxOverall:null});
assert.equal(A.read(store).secondary.cards[0].maxOverall,null);
assert.equal(A.read(store).primary.cards[0].maxOverall,111,'Limpar Secundária não toca na Principal');

const other={...card,ownerId:'pessoa-qa',level:32};
const friend=F.normalCard({...other,maxOverall:'109'});
assert.equal(friend.maxOverall,109);
assert(!Object.hasOwn(F.normalCard(other),'maxOverall'));
for(const bad of [0,151,true,1.5])assert.throws(()=>F.normalCard({...other,maxOverall:bad}),/Overall/);
assert.equal(F.normalCard({...friend,edition:'Outra edição'}).maxOverall,null);
const collection=F.validate({schema:F.SCHEMA,owners:[{id:'pessoa-qa',name:'Pessoa QA'}],cards:[friend]});
assert.equal(F.validate(JSON.parse(JSON.stringify(collection))).cards[0].maxOverall,109);
assert.equal(F.importOwner(F.empty(),F.exportOwner(collection,'pessoa-qa')).cards[0].maxOverall,109,'Importação com novos IDs conserva o máximo');

const descriptor=R.catalog([original],[])[0],base={maxLevel:32,pp:62,rarity:'ÉPICA',maxOverall:102};
assert.equal(R.maximum(store,descriptor,102),102);
R.saveInfo(store,descriptor,{...base,maxOverall:110},base);
assert.equal(R.maximum(store,descriptor,102),110);
R.saveInfo(store,descriptor,{...base,maxOverall:null},base);
assert.equal(R.maximum(store,descriptor,102),null,'Limpeza explícita não ressuscita número de referência');
R.restoreInfo(store,descriptor);
assert.equal(R.maximum(store,descriptor,102),110);
R.save(store,descriptor,{cardId:'123456780',edition:'Edição nova'},true);
assert.equal(R.maximum(store,descriptor,102),null,'Referência da identidade anterior não reaparece');
R.saveInfo(store,descriptor,{...base,maxOverall:106},base);
assert.equal(R.maximum(store,descriptor,102),106,'Máximo novo pode ser informado para a identidade atual');
const mergeMemory=new Map(),mergeStore={getItem:k=>mergeMemory.get(k)??null,setItem:(k,v)=>mergeMemory.set(k,v)};
R.saveInfo(mergeStore,descriptor,{...base,maxOverall:112},base);
R.save(mergeStore,descriptor,{maxOverall:115},true);
assert.equal(R.maximum(mergeStore,descriptor,106),115,'A última declaração confirmada prevalece entre os dois editores');
assert.equal(R.infoValues(mergeStore,descriptor,base).maxOverall,115,'Editor e selo devem mostrar o mesmo máximo');
assert.equal(R.personal(original,mergeStore).max_overall,115,'Consumidores das cartas originais usam o mesmo valor atual');
R.save(mergeStore,descriptor,{maxOverall:null},true);
assert.equal(R.maximum(mergeStore,descriptor,106),null,'Limpeza confirmada não recupera a referência anterior');
R.saveInfo(mergeStore,descriptor,{...base,maxOverall:114},base);
assert.equal(R.maximum(mergeStore,descriptor,106),114);
R.save(mergeStore,descriptor,{notes:'Conferência sem editar o máximo'},true);
assert.equal(R.maximum(mergeStore,descriptor,106),114,'Salvar outros campos não apaga o máximo');
console.log('V387 PASS: máximos preservados por conta/pessoa, validação, limpeza/restauração, edição e histórico tático independente.');
