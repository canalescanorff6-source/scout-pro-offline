'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..'),web=path.join(root,'web');
const load=x=>JSON.parse(fs.readFileSync(path.join(web,x),'utf8'));
const UI=require('../web/scout-ui-v189.js');
const roster=load('SCOUT_V69_AUDITORIA.json'),photos=load('SCOUT_V184_EFHUB_241_COMPLETE.json'),physical=load('SCOUT_V101_MODELO_CORPORAL.json');
assert.equal(roster.cards.length,246);
assert.equal(photos.image_manifest.length,241);
assert.equal(photos.visual_observations.length,15);
assert.equal(physical.cartas.length,15);
const raul=roster.cards.find(x=>x.numero===2),diaz=roster.cards.find(x=>x.numero===75);
assert(raul&&diaz);
const recRaul=UI.physicalInfo({capture:2,id:raul.id},physical,photos);
assert(recRaul.verified&&recRaul.verified.card_id===raul.id,'Biotipo verificado por Card ID');
assert.equal(recRaul.playerID,false,'Nunca atribuir Player ID secreto');
const recDiaz=UI.physicalInfo({capture:75,id:diaz.id},physical,photos);
assert(recDiaz.observed,'Biotipo extraído dos prints V184');
assert.equal(recDiaz.observed.height_cm,180);
assert(!UI.matchingExternal({capture:2,id:'000123456'},physical.cartas[0]),'Nenhum biotipo de outra edição');
const ui=fs.readFileSync(path.join(web,'scout-ui-v189.js'),'utf8');
const css=fs.readFileSync(path.join(web,'scout-ui-v189.css'),'utf8');
const bridge=fs.readFileSync(path.join(web,'app-bridge.js'),'utf8');
const index=fs.readFileSync(path.join(web,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(web,'sw.js'),'utf8');
for(const label of ['Minhas Cartas','Outros Elencos','Escalação','Laboratório','Ferramentas avançadas','Como funciona a análise','Central de Técnicos'])assert(ui.includes(label),'Atalho ausente: '+label);
for(const href of ['revisao-impetos-v103.html','player-model-v101.html'])assert(ui.includes(href),
 'Ferramenta antiga não pode desaparecer com a nova entrada: '+href);
assert(ui.includes("querySelector('.hero .hero-text')"),'Homepage deve ter área de entrada');
assert(ui.includes("body.append(top,backup)"),'Ações legadas no menu Mais sem remoção');
assert(ui.includes("scout-v189-build"),'Versão visível no menu Mais');
assert(ui.includes('physicalInfo')&&ui.includes('SCOUT_V101_MODELO_CORPORAL.json'),'Biotipo no modelo comprovado');
assert(ui.includes('Não documentado')||ui.includes('não há medidas completas'),'Missing data is explicitly identified');
assert(css.includes('@media(max-width:720px)'), 'Mobile layout needs breakpoint');
assert(css.includes('body.scout-v189-method-open'),'Methodology should remain accessible');
assert(css.includes('.scout-v189-quick'), 'Simple four-entry home');
assert(css.includes('.scout-v189-dock-more[open]'),'All native dock actions accessible');
assert(css.includes('.scout-v189-measure-grid'),'Biotipo must be legible');
assert(bridge.includes('scout-ui-v189.css')&&bridge.includes('scout-ui-v189.js'),'Same UI must load on all pages');
assert(sw.includes('./scout-ui-v189.css')&&sw.includes('./scout-ui-v189.js')&&sw.includes('./scout-build-info.json'),'Offline cache');
assert(index.includes('href="app-bridge.css"'), 'Shared app bridge');
assert.equal((index.match(/class="player-card"/g)||[]).length,246);
assert.equal(fs.readdirSync(path.join(web,'fichas')).filter(x=>/\.html$/.test(x)).length,246);
assert(!ui.includes('fetch(\'https://'),'Nenhum servidor externo exigido no design');
const e=fs.readFileSync(path.join(root,'electron-builder.config.cjs'),'utf8');
const cap=load('scout-build-info.json');
assert(e.includes("'web/**/*'"),'Electron deve conter toda a UI comum');
assert(cap.mobile_web_container==='Capacitor webDir=web');
const capacitor=JSON.parse(fs.readFileSync(path.join(root,'capacitor.config.json'),'utf8'));
assert.equal(capacitor.webDir,'web');
const wf=fs.readFileSync(path.join(root,'.github/workflows/release.yml'),'utf8');
assert.equal((wf.match(/run: npm run bundle:stamp/g)||[]).length,2,'Stamp deve rodar Windows e Android');
assert(wf.includes("keys=('schema','version','git_revision','bundle_fingerprint','source_count')")&&wf.includes('different=[key for key in keys'),'CI deve impedir publicação de builds com diferenças sem confundir quebra de linha');
assert(wf.includes('scout-pro-android-teste')&&wf.includes('dist/scout-build-info.json'));
assert(!wf.includes('windows-only-ui'),'Não permitir branches de UI por OS');
cp.execFileSync(process.execPath,[path.join(root,'scripts/stamp-bundle-v189.cjs')],{cwd:root,stdio:'pipe'});
const stamp1=load('scout-build-info.json');
cp.execFileSync(process.execPath,[path.join(root,'scripts/stamp-bundle-v189.cjs')],{cwd:root,stdio:'pipe'});
const stamp2=load('scout-build-info.json');
assert.deepEqual(stamp1,stamp2,'Fingerprint precisa ser determinística');
assert(/^[a-f0-9]{20}$/.test(stamp1.bundle_fingerprint));
assert(stamp1.source_count>=45,'V214: incluir fontes V212, auditoria V213 e service worker no bundle');
const stampSource=fs.readFileSync(path.join(root,'scripts/stamp-bundle-v189.cjs'),'utf8');
assert(stampSource.includes("'sw.js'")&&stampSource.includes("'SCOUT_V213_AUDITORIA_INDIVIDUAL.json'"),'Pacotes Android/Windows precisam refletir cache e auditoria');
const morphology=load('SCOUT_V189_CORPO_EXTRAS.json');
assert.equal(morphology.entries.length,1);
assert.equal(morphology.entries[0].cap,1);
assert.equal(morphology.entries[0].dimensions.shoulder_width,8);
assert.equal(morphology.entries[0].dimensions.neck_length,7);
assert.equal(morphology.entries[0].dimensions.leg_length,11);
assert(ui.includes('SCOUT_V189_CORPO_EXTRAS.json'));
assert(sw.includes('./SCOUT_V189_CORPO_EXTRAS.json'));
assert.equal(stamp1.version,JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8')).version);
console.log('V189 OK: visual responsivo, acessibilidade, 246 fichas/241 prints intactos, 15 biotipos por ID + 15 observações, build determinístico, paridade Windows Android antes da release.');
