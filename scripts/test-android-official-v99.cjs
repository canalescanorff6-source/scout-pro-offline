'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..'),workflow=fs.readFileSync(path.join(root,'.github/workflows/release.yml'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'.github/android-signing/scout-release.enc.json'),'utf8'));
assert.equal(manifest.applicationId,'br.com.scoutpro.offline');
assert.equal(manifest.certificateSha256,'818a2b4144234810b9e6e68bddb1ccb1cf9f3b6636dcc0adc31536a4fec02c04');
assert.equal(manifest.algorithm,'aes-256-gcm');
assert(!workflow.includes('echo "$MASTER"'), 'Nunca registrar o segredo na CI');
assert(workflow.includes('secrets.ANDROID_RELEASE_SECRET'));
assert(workflow.includes("steps.keys.outputs.mode == 'master'"));
assert(workflow.includes("steps.keys.outputs.mode == 'legacy'"));
assert(workflow.includes('node scripts/official-android-sign-v99.cjs sign'));
assert(workflow.includes("needs.android.outputs.signed == 'true'"));
assert(workflow.includes('ScoutPRO-Android.apk.sha256'));
const result=cp.spawnSync(process.execPath,[path.join(root,'scripts/official-android-sign-v99.cjs'),'check'],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
const audit=JSON.parse(fs.readFileSync(path.join(root,'web/SCOUT_V69_AUDITORIA.json'),'utf8'));
assert.equal(audit.cards.length,246);assert.equal(audit.summary.with_pp,246);
assert.equal(fs.readdirSync(path.join(root,'web/cartas')).filter(n=>/^CAP_\d{3}_.+\.png$/.test(n)).length,246);
assert.equal(fs.readdirSync(path.join(root,'web/fichas')).filter(n=>/^\d{3}_.+\.html$/.test(n)).length,246);
console.log('V99 OK: identidade de assinatura protegida, segredos não publicados, release oficial condicionada a CI e 246 cartas preservadas.');
