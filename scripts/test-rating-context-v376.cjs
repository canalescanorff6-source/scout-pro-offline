memory.set('scoutpro:v307:default-manager',JSON.stringify({catalog_id:'CT-MGR-071',tactic:'posse'}));
x=C.resolve(ref,card,store,{managers});assert.equal(x.ctx.manager.id,'CT-MGR-071');
