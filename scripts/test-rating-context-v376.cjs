assert.throws(()=>C.saveTraining(ref,store,Array(10).fill(0),62,false));
assert.equal(JSON.stringify(card),before);
memory.set('scoutpro:v307:default-manager','{');assert(C.resolve(ref,card,store,{managers}).error);
memory.clear();
