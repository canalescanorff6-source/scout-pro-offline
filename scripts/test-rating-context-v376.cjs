'use strict';
const assert=require('node:assert/strict');
const C=require('../web/craque-rating-context-v376.js');
const refs=require('../web/ct376-card-references.json').cards;
const cards=require('../web/SCOUT_V69_AUDITORIA.json').cards;
const R=require('../web/craque-rating-v376.js');
const ManagerAPI=require('../web/craque-managers-v302.js');
const vm=require('node:vm'),fs=require('node:fs');
const managerSource=fs.readFileSync('web/craque-managers-v302.js','utf8'),host={};
vm.runInNewContext(managerSource,{window:host});const firstManagerAPI=host.CRAQUE_MANAGERS_V302;
vm.runInNewContext(managerSource,{window:host});
