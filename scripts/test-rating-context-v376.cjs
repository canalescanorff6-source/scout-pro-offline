assert.deepEqual(ManagerAPI.selectionRecord(null,'posse'),{catalog_id:null,tactic:'posse',cleared:true});
const memory=new Map(),store={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const ref=refs.find(c=>c.capture===90),card=cards.find(c=>c.numero===90);
const managers={find:id=>id==='CT-MGR-071'?{catalog_id:id,nome:'Kovač',name:'Kovač',boosters_EN:['Ball Control +1']}:null,proficiency:()=>90};
let x=C.resolve(ref,card,store,{managers});
