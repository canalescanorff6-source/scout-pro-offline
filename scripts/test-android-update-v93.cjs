'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'web/app-bridge.js'),'utf8');
const start=source.indexOf('const cmpVersion=');
const end=source.indexOf('async function onlineUpdate(',start);
assert(start>=0&&end>start,'Política de versão do Android deve ser isolável');
const ctx={};
vm.runInNewContext(source.slice(start,end)+';globalThis.exportsV93={cmpVersion,chooseAndroidRelease};',ctx,{timeout:2500});
const {cmpVersion,chooseAndroidRelease}=ctx.exportsV93;
assert.equal(cmpVersion('1.1.42','1.1.41'),1);
assert.equal(cmpVersion('1.1.41','1.1.41'),0);
assert.equal(cmpVersion('1.1.8','1.1.40'),-1);
const win={tag_name:'v1.1.50',assets:[{name:'ScoutPRO-Setup-1.1.50.exe',browser_download_url:'https://github.com/example/repo/a.exe'}]};
assert.equal(chooseAndroidRelease([win]),null,'Instalador Windows não é APK');
const signed={tag_name:'v1.1.48',assets:[{name:'ScoutPRO-Android.apk',browser_download_url:'https://github.com/example/repo/ScoutPRO-Android.apk'}]};
const older={tag_name:'v1.1.35',assets:[{name:'ScoutPRO-Android.apk',browser_download_url:'https://github.com/example/repo/old.apk'}]};
assert.equal(chooseAndroidRelease([win,older,signed]).release.tag_name,'v1.1.48');
assert.equal(chooseAndroidRelease([{...signed,prerelease:true},win]),null,'Pré-release não é oficial');
assert.equal(chooseAndroidRelease([{...signed,assets:[{name:'ScoutPRO-Android-TESTE.apk',browser_download_url:'https://github.com/example/a.apk'}]}]),null);
assert(source.includes('nativeAndroid()'));
assert(source.includes('document.addEventListener(\'visibilitychange\',checkWhenForeground)'));
assert(source.includes('Ainda não há APK oficial Android publicado.'));
assert(!source.includes('const url=(apk&&apk.browser_download_url)||data.html_url;'),'Fallback Windows proibido em Android');
const wf=fs.readFileSync(path.join(root,'.github/workflows/release.yml'),'utf8');
assert(wf.includes('secrets.ANDROID_KEYSTORE_BASE64'));
assert(wf.includes("needs.android.outputs.signed == 'true'"));
assert(wf.includes('python3 scripts/set-android-version.py'));
console.log('V93 OK: Android só oferece APK oficial assinado; sem confusão com release Windows e sem instalação silenciosa.');
