'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../web');
const audit=JSON.parse(fs.readFileSync(path.join(root,'SCOUT_V69_AUDITORIA.json'),'utf8'));
const expected=new Map([[243,["Anthony Gordon",31,60]],[244,["Edmond Tapsoba",27,52]],[245,["Justin Kluivert",33,64]],[246,["Eric Cantona",31,60]]]);
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const dir=path.join(root,'fichas'),names=fs.readdirSync(dir).filter(n=>/^\d{3}_.+\.html$/.test(n));
const originals=fs.readdirSync(path.join(root,'cartas')).filter(n=>/^CAP_\d{3}_.*\.png$/i.test(n));
assert.equal(names.length,246,'Todas as fichas precisam permanecer');
assert.equal(originals.length,246,'As 246 artes originais precisam permanecer');
assert.equal(audit.cards.length,246);
assert.equal(audit.summary.processed,246);
assert.equal(audit.summary.with_pp,246);
assert.equal(audit.summary.no_pp,0);
assert.equal(audit.summary.level_user_entered,85);
assert.equal(audit.cards.filter(c=>c.max_level!==undefined&&c.numero!==191).length,84,'Os 84 níveis de lotes anteriores foram preservados');
assert.equal(audit.cards.filter(c=>c.pp!==null).length,246);
assert.equal(audit.cards.filter(c=>c.pp===null).length,0);
assert.equal(audit.cards.filter(c=>c.max_level!==undefined).length,85);
const kubo=audit.cards.find(c=>c.numero===211);
assert.equal(kubo.max_level,1);assert.equal(kubo.pp,0,'Zero PP confirmado não é dado ausente');
let checked=0;
for(const c of audit.cards){
 if(!expected.has(c.numero))continue;
 checked++;const [name,level,pp]=expected.get(c.numero);
 assert.equal(c.name,name);assert.equal(c.max_level,level);assert.equal(c.pp,pp);
 assert.equal(pp,2*(level-1));assert.equal(c.niveis,null,'Não inventar build '+name);
 assert.equal(c.recomendacao,null);assert.equal(c.pp_estimado,false);
 assert.match(c.pp_origem,/usuario/);
 assert(!c.pendencias.includes('PP disponível e nível máximo'));
 const fn=names.find(s=>s.startsWith(String(c.numero).padStart(3,'0')+'_'));
 assert(fn,'Ficha desapareceu: '+name);
 const html=fs.readFileSync(path.join(dir,fn),'utf8');
 const parse=id=>{const m=html.match(new RegExp('<script[^>]*id="'+id+'"[^>]*>([\\s\\S]*?)<\\/script>','i'));assert(m,'JSON ausente '+id+' '+name);return JSON.parse(m[1]);};
 const d=parse('scout-v68-data'),lab=parse('lab-data');
 assert.equal(d.name,name);assert.equal(d.capture,c.numero);
 assert.equal(d.max_level,level);assert.equal(d.pp,pp);
 assert.equal(d.recommended_scenario,null);assert.equal(d.recommended_levels,null);
 assert.deepEqual(d.alternate_scenarios,{});
 assert.equal(lab.pp,pp);assert.equal(lab.maxLevel,level);
 assert.equal(lab.A,null);assert.equal(lab.B,null);assert.equal(lab.C,null);assert.equal(lab.recommended,null);
 assert(html.includes('PP REGISTRADOS · TREINO PENDENTE'));
 assert(!html.includes('Sem PP confirmado: edição bloqueada.'));
 const entry=index.match(new RegExp('<a class="player-card"[^>]*data-cap="'+c.numero+'"[^>]*>[\\s\\S]*?<\\/a>'));
 assert(entry,'Índice sem '+name);
 assert(entry[0].includes('<span class="pp">'+pp+' PP</span>'));
 assert(entry[0].includes('Nível máx. '+level+' · informado'));
 assert(!entry[0].includes('Aguardando PP'));
 const art=entry[0].match(/src="cartas\/(CAP_\d{3}_[^"]+\.png)"/);
 assert(art,'Referência de arte ausente: '+name);
 assert(originals.includes(art[1]),'Arquivo de arte ausente: '+art[1]);
}
assert.equal(checked,4);
console.log('V90 OK: 246 cartas com PP, nenhuma pendente, 85 níveis máximos manuais, artes e fichas intactas, Kubo 1/0 preservado.');
