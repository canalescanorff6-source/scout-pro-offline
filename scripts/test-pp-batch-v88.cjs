'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const web=path.resolve(__dirname,'../web');
const audit=JSON.parse(fs.readFileSync(path.join(web,'SCOUT_V69_AUDITORIA.json'),'utf8'));
const expected=new Map([[222,["Gerson",32,62]],[223,["Frenkie de Jong",28,54]],[224,["Manu Koné",33,64]],[226,["José María Giménez",27,52]],[227,["Kenan Yıldız",31,60]],[228,["Murilo",29,56]],[229,["Zeki Çelik",31,60]],[230,["Pape Matar Sarr",32,62]],[231,["Guglielmo Vicario",30,58]],[232,["Aymeric Laporte",31,60]]]);
const index=fs.readFileSync(path.join(web,'index.html'),'utf8');
const dir=path.join(web,'fichas'),files=fs.readdirSync(dir).filter(f=>/^\d{3}_.+\.html$/.test(f));
let verified=0;
for(const card of audit.cards){
 if(!expected.has(card.numero))continue;
 verified++;const [name,level,pp]=expected.get(card.numero);
 assert.equal(card.name,name);assert.equal(card.max_level,level);assert.equal(card.pp,pp);
 assert.equal(card.niveis,null,'Atributos inventados: '+name);
 assert.match(card.pp_origem,/usuario/);
 const entry=index.match(new RegExp('<a class="player-card"[^>]*data-cap="'+card.numero+'"[^>]*>[\\s\\S]*?<\\/a>'));
 assert(entry&&entry[0].includes('<span class="pp">'+pp+' PP</span>'),'PP incorretos no catálogo '+name);
 assert(!entry[0].includes('Aguardando PP'),name+' ainda com aviso incorreto');
 const filename=files.find(f=>f.startsWith(String(card.numero).padStart(3,'0')+'_'));
 assert(filename,'Ficha ausente: '+name);
 const html=fs.readFileSync(path.join(dir,filename),'utf8');
 const parse=id=>JSON.parse(html.match(new RegExp('<script[^>]*id="'+id+'"[^>]*>([\\s\\S]*?)<\\/script>','i'))[1]);
 const d=parse('scout-v68-data'),lab=parse('lab-data');
 assert.equal(d.capture,card.numero);assert.equal(d.name,name);
 assert.equal(d.max_level,level);assert.equal(d.pp,pp);assert.equal(pp,2*(level-1));
 assert.equal(d.recommended_levels,null);assert.equal(d.recommended_scenario,null);assert.deepEqual(d.alternate_scenarios,{});
 assert.equal(lab.pp,pp);assert.equal(lab.maxLevel,level);assert.equal(lab.A,null);assert.equal(lab.B,null);assert.equal(lab.C,null);
 assert(html.includes('PP REGISTRADOS · TREINO PENDENTE'));
}
assert.equal(verified,10);assert.equal(audit.cards.length,246);
assert.equal(audit.summary.with_pp,232);assert.equal(audit.summary.no_pp,14);assert.equal(audit.summary.level_user_entered,70);
console.log('V88 OK: +10 cartas com níveis máximos e PP permanentes; 232 orçamentos, 14 pendentes e 246 cartas preservadas sem builds inventadas.');
