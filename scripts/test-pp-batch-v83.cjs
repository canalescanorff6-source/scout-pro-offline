'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const web=path.resolve(__dirname,'../web');
const audit=JSON.parse(fs.readFileSync(path.join(web,'SCOUT_V69_AUDITORIA.json'),'utf8'));
const expected=new Map([[73,[29,56]],[86,[33,64]],[87,[32,62]],[101,[34,66]],[103,[31,60]],[107,[33,64]],[109,[31,60]],[112,[29,56]],[115,[28,54]],[116,[35,68]]]);
const index=fs.readFileSync(path.join(web,'index.html'),'utf8');
const folder=path.join(web,'fichas'),files=fs.readdirSync(folder);
let checked=0;
for(const card of audit.cards){
 if(!expected.has(card.numero))continue;
 checked++;const [level,pp]=expected.get(card.numero);
 assert.equal(card.max_level,level);
 assert.equal(card.pp,pp);
 assert.equal(card.niveis,null,'Não pode inventar treinamento: '+card.name);
 assert.match(card.pp_origem,/usuario/);
 const match=index.match(new RegExp('<a class="player-card"[^>]*data-cap="'+card.numero+'"[^>]*>[\\s\\S]*?<\\/a>'));
 assert(match&&match[0].includes('<span class="pp">'+pp+' PP</span>')&&!match[0].includes('Aguardando PP'),card.name+' index incorreto');
 const file=files.find(name=>name.startsWith(String(card.numero).padStart(3,'0')+'_'));
 assert(file,'Ficha ausente '+card.name);
 const html=fs.readFileSync(path.join(folder,file),'utf8');
 const extract=id=>JSON.parse(html.match(new RegExp('<script[^>]*id="'+id+'"[^>]*>([\\s\\S]*?)<\\/script>','i'))[1]);
 const d=extract('scout-v68-data'),l=extract('lab-data');
 assert.equal(d.capture,card.numero);assert.equal(d.name,card.name);assert.equal(d.max_level,level);
 assert.equal(d.pp,pp);assert.equal(pp,2*(level-1));assert.equal(l.pp,pp);assert.equal(l.maxLevel,level);
 assert.equal(d.recommended_levels,null);assert.equal(d.recommended_scenario,null);
 assert.equal(l.A,null);assert.equal(l.B,null);assert.equal(l.C,null);
 assert(html.includes('PP REGISTRADOS · TREINO PENDENTE'),card.name+' visual desatualizado');
}
assert.equal(checked,10);assert.equal(audit.cards.length,246);
assert.equal(audit.summary.with_pp,232);assert.equal(audit.summary.no_pp,14);assert.equal(audit.summary.level_user_entered,70);
console.log('V83 OK: 10 novas cartas com PP e níveis permanentes; 182 com PP, 64 pendentes; 246 cartas sem builds inventadas.');
