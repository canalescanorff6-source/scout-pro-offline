const {review}=require(file);
const card={numero:16,id:'105802492921775',name:'Dayot Upamecano',versao:'Highlight — National Teams Selection',
 pp:52,max_level:27,pp_origem:'informado_pelo_usuario_2026',posicao:'ZG',habilidades_nativas:'Interceptação; Bloqueador',niveis:null};
