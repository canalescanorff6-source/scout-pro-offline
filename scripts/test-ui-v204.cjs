'use strict';
/* V204: identidade integral, leitura de nomes/edições e mesma base offline. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('web/index.html');
const css=read('web/scout-finish-v204.css');
const names=[...html.matchAll(/class="player-name"[^>]*>(.*?)<\/div>/g)].map(m=>m[1]);
const editions=[...html.matchAll(/class="player-version"[^>]*>(.*?)<\/div>/g)].map(m=>m[1]);
assert.equal((html.match(/class="player-card"/g)||[]).length,246,'Preservar todos os 246 links');
assert.equal(names.length,246,'Preservar nomes originais');
assert.equal(editions.length,246,'Preservar edições originais');
assert(names.some(n=>n.includes('Nistelrooij')),'Nomes longos não podem ser substituídos');
assert(editions.filter(e=>e.length>60).length>=40,'Exercitar edições extensas existentes');
assert.equal((html.match(/class="player-name"/g)||[]).length,246);
assert.equal((html.match(/class="player-version"/g)||[]).length,246);
assert(css.includes('body[data-page="catalog"] #cards .player-name'),'Estilos devem ser locais');
assert(css.includes('body[data-page="catalog"] #cards .player-version'),'Edições devem ser legíveis');
assert(css.includes('white-space:normal!important'),'Desativar truncamento prévio por linha');
assert(css.includes('-webkit-line-clamp:2')&&css.includes('-webkit-line-clamp:3'),'Duas linhas de nomes, edições mobile até três');
assert(css.includes('flex-wrap:wrap')&&css.includes('.v68-mini-label'),'Metadados inferiores não podem estourar a largura');
assert(!css.includes('display:none'),'Não esconder texto ou cartas');
assert(!css.includes('url('),'CSS deve ser integralmente offline');
const bridge=read('web/app-bridge.js'),sw=read('web/sw.js'),stamp=read('scripts/stamp-bundle-v189.cjs');
assert(bridge.includes("v189Root+'scout-finish-v204.css'"),'Estilo compartilhado Electron/Capacitor');
assert(sw.includes("'./scout-finish-v204.css'"),'Asset no service worker offline');
assert(stamp.includes("'scout-finish-v204.css'"),'Asset no fingerprint Windows/Android');
assert(sw.includes('v204-card-legibility'),'Cache V204 diferente');
console.log('V204 OK: 246 nomes/edições preservados, leitura premium responsiva e cache compartilhado.');
