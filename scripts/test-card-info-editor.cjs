'use strict';
const assert=require('node:assert/strict');
const R=require('../web/craque-card-review-v379.js');
const originals=require('../web/SCOUT_V69_AUDITORIA.json').cards;
const refs=require('../web/ct376-card-references.json').cards;
const C=require('../web/craque-rating-context-v376.js'),P=require('../web/craque-positional-v311.js');
const raw=originals[0],card=R.catalog([raw],[])[0],ref=refs.find(c=>c.key===card.key);
const memory=new Map(),store={getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const base={maxLevel:32,pp:62,rarity:'ÉPICA',maxOverall:102};
// Missing editor must fail here; the remaining assertions exercise real storage and consumers.
assert.deepEqual(R.infoValues(store,card,base),base);
const review=R.save(store,card,{maxLevel:32,pp:62,training:[0,4,4,4,0,0,0,0,0,0],skills:['Passe de primeira','','','',''],equipmentReviewed:true},true);
R.save(store,card,{maxLevel:33,notes:'Rascunho não publicado'},false);
const draft=store.getItem(R.PREFIX+card.key),canonical=JSON.stringify(originals);
R.saveInfo(store,card,{maxLevel:'34',pp:'66',rarity:'BIG TIME',maxOverall:'108'},base);
assert.equal(store.getItem(R.PREFIX+card.key),draft,'Editor não pode sobrescrever rascunho ou conferência ativa');
assert.equal(R.infoRead(store,card).pp,66);
assert.equal(R.infoValues(store,card,base).maxOverall,108);
const applied=R.personal(raw,store);
assert.equal(applied.id,raw.id);assert.equal(applied.versao,raw.versao);
assert.equal(applied.max_level,34);assert.equal(applied.pp,66);assert.equal(applied.rarity,'BIG TIME');
assert.deepEqual(applied.niveis,review.training);
assert.equal(P.fromPersonal(raw,null,store).pp,66);
assert.equal(C.resolve(ref,raw,store).ctx.budget,66);
assert.equal(C.resolve(ref,raw,store).maxLevel,34);
R.saveInfo(store,card,{...base,maxOverall:''},base);
assert.equal(R.infoValues(store,card,base).maxOverall,null,'Limpar OVR não recupera silenciosamente o anterior');
R.restoreInfo(store,card);
assert.equal(R.infoValues(store,card,base).maxOverall,108);
R.saveInfo(store,card,{...base,maxLevel:30,pp:1},base);
assert.equal(R.infoRead(store,card).mathOk,false);
assert.equal(P.fromPersonal(raw,null,store).pp,null,'PP incoerentes não alimentam sugestões');
assert.equal(P.fromPersonal(raw,null,store).level,null,'Nível incoerente não pode regenerar PP automaticamente');
assert.equal(P.fromPersonal(raw,null,store).publicMaxLevel,null);
assert.equal(C.resolve(ref,raw,store).ctx.budget,null);
assert.match(C.resolve(ref,raw,store).error,/PP|nível/);
assert.deepEqual(R.personal(raw,store).niveis,review.training,'Nem conflito altera treino aprovado');
for(const bad of [{maxLevel:''},{pp:''},{maxLevel:1.5},{pp:-1},{pp:1001},{maxOverall:151},{rarity:'  '}])
 assert.throws(()=>R.saveInfo(store,card,{...base,...bad},base));
assert.throws(()=>R.saveInfo({getItem:()=>null,setItem(){throw Error('Sem espaço')}},card,base,base),/Sem espaço/);
assert.equal(R.infoRead(store,{...card,edition:'Outra edição'}),null);
const savedInfo=R.infoRead(store,card);
R.save(store,card,{cardId:'123456789',edition:'Edição substituída'},true);
assert.equal(R.infoRead(store,card),null,'Editor antigo não migra para identidade substituída');
assert.equal(savedInfo.pp,1);
assert.equal(JSON.stringify(originals),canonical);
const owned=require('../web/ct364-owned-cards.json').cards[0],od=R.catalog([],[owned])[0];
R.saveInfo(store,od,{...base,maxLevel:33,pp:64},base);
assert.equal(R.owned(owned,store).maxLevel,33);
assert.equal(R.owned(owned,store).pp,64);
R.restoreInfo(store,od);
assert.equal(R.infoValues(store,od,base).maxLevel,32);
// A smaller budget keeps a previously confirmed vector on disk, but cannot
// calculate a valid sheet from training that exceeds the new budget.
const clean=new Map(),s={getItem:k=>clean.get(k)||null,setItem:(k,v)=>clean.set(k,v)};
C.saveTraining(ref,s,[0,4,4,4,0,0,0,0,0,0],62,true);
const trainingBefore=s.getItem(C.trainingKey(ref));
R.saveInfo(s,card,{...base,maxLevel:34,pp:66},base);
assert.deepEqual(C.resolve(ref,raw,s).ctx.training,[0,4,4,4,0,0,0,0,0,0]);
R.saveInfo(s,card,{...base,maxLevel:2,pp:2},base);
assert.equal(C.resolve(ref,raw,s).ctx.training,null);
assert.match(C.resolve(ref,raw,s).error,/PP/);
assert.equal(s.getItem(C.trainingKey(ref)),trainingBefore);
console.log('Editor PASS: persistência, restauração, identidade, rascunhos, OVR separado, PP e fichas originais/próprias.');
