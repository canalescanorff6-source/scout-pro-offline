'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const web=path.resolve(__dirname,'../web');
const audit=JSON.parse(fs.readFileSync(path.join(web,'SCOUT_V69_AUDITORIA.json'),'utf8'));
const expected=new Map([[233,["Nicola Zalewski",36,70]],[234,["Kakita Yuki",32,62]],[235,["Kumasaka Koki",33,64]],[236,["Samuel Eto'o",34,66]],[237,["Piero Hincapié",33,64]],[238,["Mateus Fernandes",35,68]],[239,["Alexander Isak",31,60]],[240,["Gonçalo Ramos",32,62]],[241,["Federico Valverde",31,60]],[242,["Maghnes Akliouche",32,62]]]);
assert.equal(audit.cards.length,246);
assert.equal(audit.summary.processed,246);
assert.equal(audit.summary.with_pp,242);
assert.equal(audit.summary.no_pp,4);
assert.equal(audit.summary.level_user_entered,80);
assert.equal(audit.cards.filter(c=>c.pp!==null).length,242);
assert.deepEqual(audit.cards.filter(c=>c.pp===null).map(c=>c.numero),[243,244,245,246]);
const kubo=audit.cards.find(c=>c.numero===211);
assert.equal(kubo.max_level,1);assert.equal(kubo.pp,0);
const index=fs.readFileSync(path.join(web,'index.html'),'utf8');
const dir=path.join(web,'fichas'),files=fs.readdirSync(dir).filter(f=>/^\d{3}_.+\.html$/.test(f));
let checked=0;
for(const c of audit.cards){
 if(!expected.has(c.numero))continue;
 checked++;
 const [name,level,pp]=expected.get(c.numero);
 assert.equal(c.name,name);assert.equal(c.max_level,level);assert.equal(c.pp,pp);
 assert.equal(pp,2*(level-1));
 assert.equal(c.niveis,null,'Build fictícia '+name);
 assert.equal(c.recomendacao,null);
 assert.equal(c.pp_estimado,false);
 assert.match(c.pp_origem,/usuario/);
 assert(!c.pendencias.includes('PP disponível e nível máximo'));
 const filename=files.find(f=>f.startsWith(String(c.numero).padStart(3,'0')+'_'));
 assert(filename,'Ficha ausente '+name);
 const html=fs.readFileSync(path.join(dir,filename),'utf8');
 const parse=id=>{
  const m=html.match(new RegExp('<script[^>]*id="'+id+'"[^>]*>([\\s\\S]*?)<\\/script>','i'));
  assert(m,'JSON ausente '+id+' '+name);
  return JSON.parse(m[1]);
 };
 const d=parse('scout-v68-data'),lab=parse('lab-data');
 assert.equal(d.capture,c.numero);assert.equal(d.name,name);
 assert.equal(d.max_level,level);assert.equal(d.pp,pp);assert.equal(d.pp_estimated,false);
 assert.equal(d.recommended_levels,null);assert.equal(d.recommended_scenario,null);
 assert.deepEqual(d.alternate_scenarios,{});
 assert.equal(lab.pp,pp);assert.equal(lab.maxLevel,level);
 assert.equal(lab.A,null);assert.equal(lab.B,null);assert.equal(lab.C,null);
 assert.equal(lab.recommended,null);
 assert(html.includes('PP REGISTRADOS · TREINO PENDENTE'));
 assert(!html.includes('Sem PP confirmado: edição bloqueada.'));
 const entry=index.match(new RegExp('<a class="player-card"[^>]*data-cap="'+c.numero+'"[^>]*>[\\s\\S]*?<\\/a>'));
 assert(entry,'Faltou carta no índice '+name);
 assert(entry[0].includes('<span class="pp">'+pp+' PP</span>'));
 assert(entry[0].includes('Nível máx. '+level+' · informado'));
 assert(!entry[0].includes('Aguardando PP'));
 assert(entry[0].includes('src="cartas/CAP_'+c.numero+'_'),'Arte original ausente '+name);
}
assert.equal(checked,10);
console.log('V89 OK: lote 8 (233-242), 242 com PP, 4 pendentes, 80 níveis manuais; 246 cartas e Kubo 1/0 preservados.');
