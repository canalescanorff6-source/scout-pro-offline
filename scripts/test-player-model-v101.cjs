'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const web=path.resolve(__dirname,'../web'),core=require(path.join(web,'player-model-v101-core.js'));
const audit=JSON.parse(fs.readFileSync(path.join(web,'SCOUT_V98_AUDITORIA_TATICA.json'),'utf8'));
const physical=JSON.parse(fs.readFileSync(path.join(web,'SCOUT_V101_MODELO_CORPORAL.json'),'utf8'));
assert.equal(audit.total,246);assert.equal(audit.cartas.length,246);
assert.equal(physical.total_roster,246);assert.equal(physical.version,'V101');
assert.equal(physical.verificados,physical.cartas.length);
assert(physical.cartas.length>=10&&physical.cartas.length<246,'No invented full coverage');
const nums=new Set(),ids=new Set();
for(const c of physical.cartas){
 assert(!nums.has(c.numero));nums.add(c.numero);assert(!ids.has(c.card_id));ids.add(c.card_id);
 const original=audit.cartas.find(x=>x.numero===c.numero);
 assert(core.match(original,c),'Exact edition must match Card ID #'+c.numero);
 assert.equal(c.player_id_animacao,null,'Player ID is not the card ID');
 assert(c.url.startsWith('https://pesdb.net/efootball/players/'));
 assert(c.url.endsWith('-'+c.card_id));
 assert(c.altura_cm>=120&&c.altura_cm<=230);
 assert(c.peso_kg>=35&&c.peso_kg<=180);
 assert(c.modelo_corporal.comprimento_perna>=0);
 const m=core.combine(original,c,null);
 assert(m.verified&&m.morphologyComplete&&m.bodyModelComplete);
 assert(!m.playerIDVerified&&m.gameplayStatus.includes('não comprovado'));
 const mismatch={...c,card_id:'987654321'};
 assert(!core.match(original,mismatch));
 assert(!core.combine(original,mismatch,null).verified);
}
const r=core.state(audit.cartas,physical.cartas,{});
assert.equal(r.total,246);assert.equal(r.verified,physical.verificados);assert.equal(r.pending,246-physical.verificados);
assert.equal(core.validPatch({altura_cm:999}),null);
assert.equal(core.validPatch({pe_dominante:'ambos'}),null);
assert.equal(core.validPatch({modelo_corporal:{comprimento_perna:-1}}),null);
assert.equal(core.validPatch({nota:'x'.repeat(1600)}),null);
assert.deepEqual(core.validPatch({altura_cm:180,modelo_corporal:{comprimento_perna:10}}),{altura_cm:180,modelo_corporal:{comprimento_perna:10}});
const sample=audit.cartas.find(c=>c.numero===39),observed=physical.cartas.find(c=>c.numero===39);
const local=core.validPatch({altura_cm:184,nota:'Teste manual'});
const merge=core.combine(sample,observed,local);
assert(merge.verified&&merge.overridden);assert.equal(merge.fields.altura_cm,184);
assert.equal(observed.altura_cm,183,'Local override must not mutate trusted catalogue');
const key=core.key(sample);
assert(key.startsWith('scoutpro:v101:body:39:'));
assert(core.validObservation({tatica:'posse',formacao:'4-3-1-2',giro:3,primeiro_toque:3,aceleracao:3,protecao:3,cobertura:3,nota:''}));
assert.equal(core.validObservation({tatica:'posse',formacao:'4-3-1-2EXTRA',giro:3,primeiro_toque:3,aceleracao:3,protecao:3,cobertura:3,nota:''}),null);
assert.equal(core.validObservation({tatica:'posse',formacao:'4-3-1-2',giro:6,primeiro_toque:3,aceleracao:3,protecao:3,cobertura:3,nota:''}),null);
const html=fs.readFileSync(path.join(web,'player-model-v101.html'),'utf8');
const ui=fs.readFileSync(path.join(web,'player-model-v101-ui.js'),'utf8');
const index=fs.readFileSync(path.join(web,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(web,'sw.js'),'utf8');
assert(html.includes('id="body-form"')&&html.includes('id="game-form"'));
assert(html.includes('app-bridge.js'),'Backup must apply on Android/Windows');
assert(ui.includes('scoutpro:v101:games:'));
assert(!ui.includes('localStorage.setItem('+'scoutpro:v67'));
assert(index.includes('player-model-v101.html'),'Main link missing');
assert(sw.includes('player-model-v101.html')&&sw.includes('SCOUT_V101_MODELO_CORPORAL.json'),'Offline shell incomplete');
console.log('V101 OK: '+physical.cartas.length+' exact-edition physique records; '+r.pending+' still pending; Player ID never fabricated; 246 cards preserved.');
