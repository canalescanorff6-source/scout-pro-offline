'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const js=fs.readFileSync(path.join(root,'web/app-bridge.js'),'utf8');
const css=fs.readFileSync(path.join(root,'web/app-bridge.css'),'utf8');
const index=fs.readFileSync(path.join(root,'web/index.html'),'utf8');
const expected=['scout-native-android','scout-android-toast','scoutToastTimer','scoutToast.hidden=true','scout-app-bar'];
for(const token of expected)assert(js.includes(token),'Android behavior missing '+token);
assert(js.includes("window.Capacitor?.getPlatform?.()==='android'"),'Native Android feature detection required');
assert(js.includes("btn.textContent='Atualizar APK'"),'Update APK button must remain functional');
assert(js.includes("btn.onclick=()=>{try{openAndroidUpdater()}"),'Android update panel must be connected before native initialization');
assert(js.includes("bar.querySelector('#scout-top').onclick"),'Top navigation must be preserved');
assert(js.includes("bar.querySelector('#scout-back')"),'Back navigation must be preserved');
assert(css.includes('body.scout-native-android{'),'Android-only CSS required');
assert(css.includes('--scout-native-safe-top'),'Status bar safe offset required');
assert(css.includes('top:var(--scout-native-safe-top)'),'Sticky header must respect status bar');
assert(css.includes('padding-bottom:calc(90px + env(safe-area-inset-bottom, 0px))!important'),'Bottom scrolling clearance');
assert(css.includes('body.scout-native-android #scout-app-bar .scout-page-actions'),'Navigation must have native dock styles');
assert(css.includes('display:contents!important'),'No multi-row dock');
assert(css.includes('body.scout-native-android #scout-app-bar>div:first-child'),'Hide persistent banner on Android');
assert(css.includes('#scout-android-toast[hidden]'),'Toast must be dismissible/temporary');
assert(css.includes('body.scout-native-android .topbar .brand-copy b'),'Responsive brand required');
assert(!css.includes('body:not(.scout-native-android) .topbar'),'Desktop CSS must remain untouched');
assert(index.includes('href="app-bridge.css"'),'Layout CSS loaded on index');
const cards=fs.readdirSync(path.join(root,'web/cartas')).filter(x=>/^CAP_\d{3}_.+\.png$/i.test(x));
const fichas=fs.readdirSync(path.join(root,'web/fichas')).filter(x=>/^\d{3}_.+\.html$/i.test(x));
assert.equal(cards.length,246);assert.equal(fichas.length,246);
console.log('V97 OK: compact Android dock, separate temporary update notice, status bar safe area, intact update/back/roster and 246 cards.');
