'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const managers=require('../web/craque-managers-v302.js');
const hub=require('../web/craque-manager-hub-v307.js');
const source=JSON.parse(zlib.gunzipSync(Buffer.from(read('web/craque-manager-catalog-v302.gz.b64').trim(),'base64')).toString('utf8'));
const items=managers.validate(source).tecnicos;
assert.equal(items.length,70);
const featured=hub.pick(items,{scope:'featured'});
assert.equal(featured.length,22,'Todos os 22 destaques devem aparecer sem filtros');
assert.equal(new Set(featured.map(c=>c.catalog_id)).size,22);
assert.equal(hub.pick(items,{scope:'all'}).length,70);
const only90=hub.pick(items,{scope:'featured',min:90});
assert(only90.length>=4&&only90.every(c=>managers.STYLES.some(s=>managers.proficiency(c,s.id)>=90)));
const overloaded=hub.pick(items,{scope:'featured',style:'overload',min:85});
assert(overloaded.some(c=>c.catalog_id==='CT-MGR-003'),'Makino 88 Sobreposição deve aparecer');
assert(overloaded.some(c=>c.catalog_id==='CT-MGR-007'),'Lampard 89 Sobreposição deve aparecer');
const caseSearch=hub.pick(items,{scope:'featured',query:'klopp'});
assert.equal(caseSearch.length,2,'Duas versões de Klopp, sem colapso por nome');
const dual=hub.pick(items,{scope:'featured',dual:true});
assert(dual.some(c=>c.catalog_id==='CT-MGR-013'),'Tuchel 90/89 disponível');
assert(!dual.some(c=>c.catalog_id==='CT-MGR-001'),'Klopp 90/83 não deve ser falsamente dual 85+');
const fake={map:new Map(),getItem(k){return this.map.get(k)||null},setItem(k,v){this.map.set(k,v)},removeItem(k){this.map.delete(k)}};
assert.equal(hub.toggleStored(hub.FAVORITES,'CT-MGR-013',fake),true);
assert.equal(hub.toggleStored(hub.FAVORITES,'CT-MGR-013',fake),false);
assert.equal(hub.fromStore(hub.FAVORITES,fake).size,0);
assert.equal(hub.safePortrait('https://example.com/photo.jpg'),null,'Bloquear hotlinks em retratos');
assert.equal(hub.safePortrait('data:image/svg+xml,<svg>'),null,'Bloquear SVG não confiável');
const key=hub.portraitKey('CT-MGR-013');
fake.setItem(key,'data:image/jpeg;base64,YWJj');
assert.equal(hub.portraitFor('CT-MGR-013',fake),'data:image/jpeg;base64,YWJj');
assert.equal(hub.portraitFor('CT-MGR-001',fake),null,'Imagem não deve vazar para outra edição');
for(const name of ['tecnicos-v307.html','craque-manager-hub-v307.js','craque-managers-v307.css']){
 assert(read('web/sw.js').includes("'./"+name+"'"),'Cache offline ausente '+name);
 assert(read('scripts/stamp-bundle-v189.cjs').includes("'"+name+"'"),'Fingerprint ausente '+name);
}
const index=read('web/pwa.js');assert(index.includes('tecnicos-v307.html'));
const others=read('web/outros-elencos-v227.html');
assert(others.includes('href="tecnicos-v307.html"'));
const main=read('web/craque-managers-v302.js');
assert(main.includes('ct-manager-six-styles')&&main.includes('portraitFor'));
assert(read('web/craque-friends-training-ui-v228.js').includes('friend-manager-scores'));
assert.equal(JSON.parse(read('web/SCOUT_V69_AUDITORIA.json')).cards.length,246);
console.log('V307 PASS: 22 técnicos no destaque, 70 na base, seis estilos, filtros 90/85, 2 Klopp, favoritos e retratos isolados, Android/Windows offline, 246 cartas intocadas.');
